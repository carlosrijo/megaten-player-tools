//! Port of `src/Data/Json.cs`: small helpers for reading loosely-typed JSON and writing ordered JSON.
//!
//! C# `JsonNode` -> [`serde_json::Value`] (with `preserve_order`); `JsonObject`/`Row` -> [`Row`] (a `Map`, insertion
//! ordered). A JSON `null` and a missing property are the same thing in C# (both read as `null`), so the helpers take
//! `Option<&Value>` and treat `Value::Null` as `None`; chain lookups with [`At::at`] (`n["a"]?["b"]` -> `n.at("a").at("b")`).
//!
//! Writing: `JsonSerializer.Serialize(value, Out)` wrote 2-space indented JSON with `Environment.NewLine` (\r\n on
//! Windows) and the relaxed escaping ([`Escape::Relaxed`]); the default serializer options (characters.json, config.json)
//! use [`Escape::Default`]. Both escape the same characters as .NET 10 does (the tables were generated by running the
//! encoders). A number built from a double is written like .NET (`1.0` -> `1`, shortest round-trip text, see
//! [`crate::fmt::g`]); a JSON number read from a file and written back keeps no "raw text" as .NET's JsonNode did (`1.0`
//! comes back as `1`).

use std::path::Path;

use serde_json::{Map, Value};

use crate::Result;

/// Insertion-ordered JSON object for output rows (C# `Row`: an ordered dictionary with ordinal keys).
pub type Row = Map<String, Value>;

/// Which JSON string escaping to write.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Escape {
    /// `JavaScriptEncoder.UnsafeRelaxedJsonEscaping` (`Json.Out`): keeps Japanese and HTML characters readable.
    Relaxed,
    /// `JsonSerializerOptions` default encoder: every non-ASCII character and `<>&'+` and the backtick become \uXXXX.
    Default,
}

// ---------- reading ----------

/// `File.ReadAllText` + `JsonNode.Parse`. A leading BOM is dropped. A file holding `null` gives `Value::Null`.
pub fn load(path: impl AsRef<Path>) -> Result<Value> {
    let text = read_all_text(path.as_ref())?;
    parse(&text)
}

/// `JsonNode.Parse(text)`.
pub fn parse(text: &str) -> Result<Value> {
    Ok(serde_json::from_str(text.trim_start_matches('\u{feff}'))?)
}

/// `File.ReadAllText`: UTF-8 (a BOM is detected and dropped). Invalid bytes become U+FFFD like .NET's decoder.
pub fn read_all_text(path: &Path) -> Result<String> {
    let bytes = std::fs::read(path)?;
    Ok(decode_text(&bytes))
}

/// The text of a file's bytes as `StreamReader` with BOM detection reads it (UTF-8, UTF-16 LE/BE with a BOM).
pub fn decode_text(bytes: &[u8]) -> String {
    if bytes.starts_with(&[0xFF, 0xFE]) {
        let units: Vec<u16> = bytes[2..].chunks_exact(2).map(|c| u16::from_le_bytes([c[0], c[1]])).collect();
        return String::from_utf16_lossy(&units);
    }
    if bytes.starts_with(&[0xFE, 0xFF]) {
        let units: Vec<u16> = bytes[2..].chunks_exact(2).map(|c| u16::from_be_bytes([c[0], c[1]])).collect();
        return String::from_utf16_lossy(&units);
    }
    let b = bytes.strip_prefix(&[0xEF, 0xBB, 0xBF]).unwrap_or(bytes);
    String::from_utf8_lossy(b).into_owned()
}

/// `File.ReadLines` on a text: lines split on \r\n, \n or \r (no empty last line for a trailing newline).
pub fn lines(text: &str) -> Vec<&str> {
    let mut res = Vec::new();
    let b = text.as_bytes();
    let (mut start, mut i) = (0, 0);
    while i < b.len() {
        match b[i] {
            b'\n' => {
                res.push(&text[start..i]);
                i += 1;
                start = i;
            }
            b'\r' => {
                res.push(&text[start..i]);
                i += if b.get(i + 1) == Some(&b'\n') { 2 } else { 1 };
                start = i;
            }
            _ => i += 1,
        }
    }
    if start < b.len() {
        res.push(&text[start..]);
    }
    res
}

/// A property of a JSON object, or `None` when missing, null, or when the node is not an object (C# `node["key"]`;
/// where C# would throw on a non-object this gives `None`).
pub trait At<'a> {
    fn at(self, key: &str) -> Option<&'a Value>;
    /// An array element (C# `node[index]`), `None` when out of range, null or not an array.
    fn idx(self, index: usize) -> Option<&'a Value>;
}

impl<'a> At<'a> for &'a Value {
    fn at(self, key: &str) -> Option<&'a Value> {
        self.get(key).filter(|v| !v.is_null())
    }
    fn idx(self, index: usize) -> Option<&'a Value> {
        self.as_array().and_then(|a| a.get(index)).filter(|v| !v.is_null())
    }
}

impl<'a> At<'a> for Option<&'a Value> {
    fn at(self, key: &str) -> Option<&'a Value> {
        self.and_then(|v| v.at(key))
    }
    fn idx(self, index: usize) -> Option<&'a Value> {
        self.and_then(|v| v.idx(index))
    }
}

/// `node.AsObject()`: an error when the node is not a JSON object.
pub fn as_object(n: Option<&Value>) -> Result<&Map<String, Value>> {
    match n {
        Some(Value::Object(m)) => Ok(m),
        _ => Err(anyhow::anyhow!("The node must be of type 'JsonObject'.")),
    }
}

/// `Json.Num`: a number (or a string holding one) as a double; `None` for anything else.
pub fn num(n: Option<&Value>) -> Option<f64> {
    match n? {
        Value::Number(x) => x.as_f64(),
        Value::String(s) => parse_double(s),
        _ => None,
    }
}

/// `double.TryParse(s, NumberStyles.Float, InvariantCulture)`: white space around the number is only the ASCII kind .NET
/// allows (9-13 and 32; not U+00A0 and the like), "NaN" parses.
fn parse_double(s: &str) -> Option<f64> {
    let t = s.trim_matches(|c: char| matches!(c, '\t'..='\r' | ' ' | '\0'));
    if t.chars().next().is_none_or(char::is_whitespace) || t.chars().last().is_none_or(char::is_whitespace) {
        return None;
    }
    if t.eq_ignore_ascii_case("nan") {
        return Some(f64::NAN);
    }
    crate::fmt::parse_f64(t)
}

/// `Json.Int(n)` (default 0): the number truncated toward zero (saturating, NaN -> 0 like .NET 9+).
pub fn int(n: Option<&Value>) -> i32 {
    int_or(n, 0)
}

/// `Json.Int(n, dflt)`.
pub fn int_or(n: Option<&Value>, dflt: i32) -> i32 {
    num(n).map(|d| d as i32).unwrap_or(dflt)
}

/// `Json.Str`: a string as is, a number as .NET shows a double ("5", "1.5", "1E+21"), a bool as "true"/"false";
/// `None` for null, objects and arrays.
pub fn str(n: Option<&Value>) -> Option<String> {
    match n? {
        Value::String(s) => Some(s.clone()),
        Value::Number(x) => Some(crate::fmt::g(x.as_f64()?)),
        Value::Bool(b) => Some(if *b { "true" } else { "false" }.to_string()),
        _ => None,
    }
}

/// `Json.Truthy`: false for null, false, "" and "false" (any case), 0 and an empty array; true otherwise.
pub fn truthy(n: Option<&Value>) -> bool {
    match n {
        None | Some(Value::Null) => false,
        Some(Value::Bool(b)) => *b,
        Some(Value::String(s)) => !s.is_empty() && !s.eq_ignore_ascii_case("false"),
        Some(Value::Number(x)) => x.as_f64().is_some_and(|d| d != 0.0),
        Some(Value::Array(a)) => !a.is_empty(),
        Some(Value::Object(_)) => true,
    }
}

/// `Json.Arr`: the non-null elements of an array; nothing for anything that is not an array.
pub fn arr(n: Option<&Value>) -> impl Iterator<Item = &Value> {
    n.and_then(|v| v.as_array()).into_iter().flatten().filter(|v| !v.is_null())
}

/// `JsonNode.ToString()`: a string without quotes, other values as JSON text; `None` for null.
pub fn node_to_string(n: Option<&Value>) -> Option<String> {
    match n? {
        Value::Null => None,
        Value::String(s) => Some(s.clone()),
        v => Some(serialize(v, Escape::Default, true)),
    }
}

// ---------- writing ----------

/// `JsonSerializer.Serialize(value, Json.Out)`: indented, relaxed escaping.
pub fn to_string(value: &Value) -> String {
    serialize(value, Escape::Relaxed, true)
}

/// `Json.Save`: creates the folder, writes UTF-8 without BOM.
pub fn save(path: impl AsRef<Path>, value: &Value) -> Result<()> {
    let path = path.as_ref();
    create_parent(path)?;
    write_atomic(path, to_string(value))?;
    Ok(())
}

/// Write a whole file safely: into `<name>.tmp` beside it first, then swap it in. A program killed halfway leaves
/// the old file as it was (a plain write empties the file first, so a kill there lost it). A file another program holds
/// open (the CSV in Excel) gives a message for the person instead of an OS error.
pub fn write_atomic(path: impl AsRef<Path>, contents: impl AsRef<[u8]>) -> Result<()> {
    let path = path.as_ref();
    let mut tmp_name = path.file_name().map(|n| n.to_os_string()).unwrap_or_default();
    tmp_name.push(".tmp");
    let tmp = path.with_file_name(tmp_name);
    if let Err(e) = std::fs::write(&tmp, contents) {
        let _ = std::fs::remove_file(&tmp);
        return Err(explain_write_error(path, e));
    }
    if let Err(e) = std::fs::rename(&tmp, path) {
        let _ = std::fs::remove_file(&tmp);
        return Err(explain_write_error(path, e));
    }
    Ok(())
}

/// True when another program holds the file so it can't be written (Excel keeps an open CSV locked).
pub fn is_locked_error(e: &std::io::Error) -> bool {
    // 32 ERROR_SHARING_VIOLATION, 33 ERROR_LOCK_VIOLATION, 5 ERROR_ACCESS_DENIED (replacing a file that is open)
    matches!(e.raw_os_error(), Some(32) | Some(33) | Some(5))
}

/// The error for a failed write: a plain message when the file is held by another program, else the OS error.
pub fn explain_write_error(path: &Path, e: std::io::Error) -> anyhow::Error {
    if is_locked_error(&e) && path.exists() {
        crate::error::user_error(format!(
            "{} is open in another program (Excel?), so it can't be saved. Close it there, then try again.",
            path.display()
        ))
    } else {
        anyhow::Error::new(e).context(format!("writing {}", path.display()))
    }
}

/// Check up front that an existing file can be written, before anything else is changed (a snapshot checks its CSV
/// first, so a CSV open in Excel stops it before the caches move on). A missing file is fine: it will be created.
pub fn ensure_writable(path: impl AsRef<Path>) -> Result<()> {
    let path = path.as_ref();
    if !path.exists() {
        return Ok(());
    }
    match std::fs::OpenOptions::new().append(true).open(path) {
        Ok(_) => Ok(()),
        Err(e) => Err(explain_write_error(path, e)),
    }
}

/// `Json.SaveIfChanged`: save, but leave the file alone when it already holds exactly this (see the C# comment: rewriting a
/// big file within seconds of its last write stalled ~0.5 s). Not for files whose date means something.
pub fn save_if_changed(path: impl AsRef<Path>, value: &Value) -> Result<()> {
    let path = path.as_ref();
    let text = to_string(value);
    if path.exists() {
        // catch (IOException) { }: an unreadable file is simply rewritten
        if let Ok(old) = read_all_text(path) {
            if old == text {
                return Ok(());
            }
        }
    }
    create_parent(path)?;
    write_atomic(path, text)?;
    Ok(())
}

/// `Directory.CreateDirectory(Path.GetDirectoryName(path))`.
pub fn create_parent(path: &Path) -> Result<()> {
    if let Some(dir) = path.parent() {
        if !dir.as_os_str().is_empty() {
            std::fs::create_dir_all(dir)?;
        }
    }
    Ok(())
}

/// Serialize like System.Text.Json: `indented` = WriteIndented (2 spaces, \r\n); not indented = compact.
pub fn serialize(value: &Value, esc: Escape, indented: bool) -> String {
    let mut out = String::new();
    write_value(&mut out, value, esc, indented, 0);
    out
}

fn newline(out: &mut String, indented: bool, depth: usize) {
    if indented {
        out.push_str("\r\n");
        for _ in 0..depth {
            out.push_str("  ");
        }
    }
}

fn write_value(out: &mut String, v: &Value, esc: Escape, ind: bool, depth: usize) {
    match v {
        Value::Null => out.push_str("null"),
        Value::Bool(b) => out.push_str(if *b { "true" } else { "false" }),
        Value::Number(n) => match (n.as_i64(), n.as_u64()) {
            (Some(i), _) => out.push_str(&i.to_string()),
            (_, Some(u)) => out.push_str(&u.to_string()),
            _ => out.push_str(&crate::fmt::g(n.as_f64().unwrap_or(0.0))),
        },
        Value::String(s) => write_string(out, s, esc),
        Value::Array(a) => {
            if a.is_empty() {
                out.push_str("[]");
                return;
            }
            out.push('[');
            for (i, x) in a.iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                newline(out, ind, depth + 1);
                write_value(out, x, esc, ind, depth + 1);
            }
            newline(out, ind, depth);
            out.push(']');
        }
        Value::Object(m) => {
            if m.is_empty() {
                out.push_str("{}");
                return;
            }
            out.push('{');
            for (i, (k, x)) in m.iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                newline(out, ind, depth + 1);
                write_string(out, k, esc);
                out.push(':');
                if ind {
                    out.push(' ');
                }
                write_value(out, x, esc, ind, depth + 1);
            }
            newline(out, ind, depth);
            out.push('}');
        }
    }
}

/// A JSON string literal with .NET's escaping.
pub fn write_string(out: &mut String, s: &str, esc: Escape) {
    out.push('"');
    for c in s.chars() {
        let cp = c as u32;
        match c {
            '\\' => out.push_str("\\\\"),
            '\u{8}' => out.push_str("\\b"),
            '\t' => out.push_str("\\t"),
            '\n' => out.push_str("\\n"),
            '\u{c}' => out.push_str("\\f"),
            '\r' => out.push_str("\\r"),
            '"' if esc == Escape::Relaxed => out.push_str("\\\""),
            _ if cp < 0x80 => {
                let special = cp < 0x20 || cp == 0x7F || (esc == Escape::Default && "\"&'+<>`".contains(c));
                if special {
                    out.push_str(&format!("\\u{cp:04X}"));
                } else {
                    out.push(c);
                }
            }
            _ => {
                if cp > 0xFFFF {
                    let mut b = [0u16; 2];
                    for u in c.encode_utf16(&mut b) {
                        out.push_str(&format!("\\u{u:04X}"));
                    }
                } else if esc == Escape::Default || relaxed_escapes(cp) {
                    out.push_str(&format!("\\u{cp:04X}"));
                } else {
                    out.push(c);
                }
            }
        }
    }
    out.push('"');
}

fn relaxed_escapes(cp: u32) -> bool {
    RELAXED_ESCAPED
        .binary_search_by(|&(lo, hi)| {
            if cp < lo {
                std::cmp::Ordering::Greater
            } else if cp > hi {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

